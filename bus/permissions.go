package bus

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/nats-io/nkeys"
)

// Permissions is the allow-list for one service user. Default is deny.
type Permissions struct {
	Publish   []string
	Subscribe []string
}

// InboxPrefix is the per-service reply prefix; Connect sets it so a service can
// subscribe only to its own replies.
func InboxPrefix(service string) string { return "_INBOX." + service }

// PermissionsFor generates the permissions of a service from the registry (ADR-0011 B8):
// publish only on evt.<service>.>; pull from and acknowledge only its own durable
// consumers; subscribe to its own inbox and to the signal subjects its contract lists.
// Services never get stream or consumer creation rights.
func (r *Registry) PermissionsFor(service string) Permissions {
	p := Permissions{Subscribe: []string{InboxPrefix(service) + ".>"}}
	for _, t := range r.Types {
		if t.Publisher == service {
			p.Publish = append(p.Publish, "evt."+service+".>")
			break
		}
	}
	for _, c := range r.Consumptions() {
		if c.Consumer != service {
			continue
		}
		p.Publish = append(p.Publish,
			"$JS.API.CONSUMER.MSG.NEXT."+c.Stream+"."+c.Consumer,
			"$JS.API.CONSUMER.INFO."+c.Stream+"."+c.Consumer,
			// $JS.ACK.<stream>.<consumer>.<delivered>... (verified on 2.15.3, global account, no JS domain)
			"$JS.ACK."+c.Stream+"."+c.Consumer+".>",
		)
	}
	for _, t := range r.Types {
		for _, s := range t.SignalListeners {
			if s == service {
				p.Subscribe = append(p.Subscribe, t.Subject())
			}
		}
	}
	return p
}

// AdminUser is the name of the provisioning credential; no service holds it.
const AdminUser = "admin"

// DevKeys are generated nkeys: seeds are secrets; public keys go in server config.
type DevKeys struct {
	Seeds map[string][]byte // user name -> seed
	Pubs  map[string]string // user name -> public key
}

// GenerateKeys creates one user nkey per service plus the admin user.
func GenerateKeys(services []string) (*DevKeys, error) {
	k := &DevKeys{Seeds: map[string][]byte{}, Pubs: map[string]string{}}
	for _, name := range append([]string{AdminUser}, services...) {
		kp, err := nkeys.CreateUser()
		if err != nil {
			return nil, err
		}
		seed, err := kp.Seed()
		if err != nil {
			return nil, err
		}
		pub, err := kp.PublicKey()
		if err != nil {
			return nil, err
		}
		k.Seeds[name], k.Pubs[name] = seed, pub
	}
	return k, nil
}

// RenderConfig renders the NATS server "authorization" block (static config, nkey users).
// It contains only public keys.
func (r *Registry) RenderConfig(pubs map[string]string) string { return r.RenderConfigWith(pubs) }

// ExtraUser is an additional user with explicit permissions (used by tests to probe which
// permissions the client library really needs).
type ExtraUser struct {
	Name  string
	Perms Permissions
}

// RenderConfigWith is RenderConfig plus extra users.
func (r *Registry) RenderConfigWith(pubs map[string]string, extra ...ExtraUser) string {
	var b strings.Builder
	b.WriteString("# Generated by go-common bus.RenderConfig from api-specs/events. Public keys only. Do not edit.\n")
	b.WriteString("authorization {\n  users = [\n")
	fmt.Fprintf(&b, "    { nkey: %s }  # %s: full rights, provisioning only\n", pubs[AdminUser], AdminUser)
	type entry struct {
		name string
		p    Permissions
	}
	var entries []entry
	for _, svc := range r.Services() {
		entries = append(entries, entry{svc, r.PermissionsFor(svc)})
	}
	for _, x := range extra {
		entries = append(entries, entry{x.Name, x.Perms})
	}
	for _, en := range entries {
		svc, p := en.name, en.p
		fmt.Fprintf(&b, "    {\n      nkey: %s  # %s\n      permissions: {\n", pubs[svc], svc)
		if len(p.Publish) > 0 {
			fmt.Fprintf(&b, "        publish: { allow: %s }\n", list(p.Publish))
		} else {
			b.WriteString("        publish: { deny: [\">\"] }\n")
		}
		fmt.Fprintf(&b, "        subscribe: { allow: %s }\n", list(p.Subscribe))
		b.WriteString("      }\n    }\n")
	}
	b.WriteString("  ]\n}\n")
	return b.String()
}

func list(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = `"` + v + `"`
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// WriteDevFiles writes accounts.conf and seeds/<user>.nk (mode 0600) under dir.
func (r *Registry) WriteDevFiles(dir string, k *DevKeys, extra ...ExtraUser) error {
	if err := os.MkdirAll(filepath.Join(dir, "seeds"), 0o700); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "accounts.conf"), []byte(r.RenderConfigWith(k.Pubs, extra...)), 0o644); err != nil {
		return err
	}
	for name, seed := range k.Seeds {
		if err := os.WriteFile(filepath.Join(dir, "seeds", name+".nk"), seed, 0o600); err != nil {
			return err
		}
	}
	return nil
}
